#!/usr/bin/env bash
# Build megafloyd inside a GitHub Codespace or any devcontainer that uses
# .devcontainer/devcontainer.json. No secrets are read or written here.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
GO_DIR="$REPO_ROOT/floyd-go"
MODULE_PATH="github.com/legacy-ai/floyd"

MEGAFLOYD_HOME="${MEGAFLOYD_HOME:-$HOME/.megafloyd}"
MEGAFLOYD_DATA_DIR="${MEGAFLOYD_DATA_DIR:-$MEGAFLOYD_HOME/data}"
MEGAFLOYD_CONFIG_DIR="${MEGAFLOYD_CONFIG_DIR:-$MEGAFLOYD_HOME/config}"
MEGAFLOYD_CACHE_DIR="${MEGAFLOYD_CACHE_DIR:-$MEGAFLOYD_HOME/cache}"
MEGAFLOYD_LOG_DIR="${MEGAFLOYD_LOG_DIR:-$MEGAFLOYD_HOME/logs}"

command -v go >/dev/null 2>&1 || {
  echo "megafloyd: go is not on PATH" >&2
  exit 1
}

echo "megafloyd: creating home at $MEGAFLOYD_HOME"
mkdir -p \
  "$MEGAFLOYD_HOME/bin" \
  "$MEGAFLOYD_DATA_DIR" \
  "$MEGAFLOYD_CONFIG_DIR" \
  "$MEGAFLOYD_CACHE_DIR" \
  "$MEGAFLOYD_LOG_DIR"

# The current chassis reads FLOYD_GLOBAL_CONFIG, FLOYD_GLOBAL_DATA and
# FLOYD_CACHE_DIR. Write them to a generated file so re-running this script
# updates the values in place. The file contains paths only.
ENV_FILE="$MEGAFLOYD_HOME/env.sh"
{
  echo "# Generated by .devcontainer/post-create.sh. Contains paths only."
  printf 'export MEGAFLOYD_HOME=%q\n' "$MEGAFLOYD_HOME"
  printf 'export MEGAFLOYD_DATA_DIR=%q\n' "$MEGAFLOYD_DATA_DIR"
  printf 'export MEGAFLOYD_CONFIG_DIR=%q\n' "$MEGAFLOYD_CONFIG_DIR"
  printf 'export MEGAFLOYD_CACHE_DIR=%q\n' "$MEGAFLOYD_CACHE_DIR"
  printf 'export MEGAFLOYD_LOG_DIR=%q\n' "$MEGAFLOYD_LOG_DIR"
  printf 'export FLOYD_GLOBAL_CONFIG=%q\n' "$MEGAFLOYD_CONFIG_DIR"
  printf 'export FLOYD_GLOBAL_DATA=%q\n' "$MEGAFLOYD_DATA_DIR"
  printf 'export FLOYD_CACHE_DIR=%q\n' "$MEGAFLOYD_CACHE_DIR"
} >"$ENV_FILE"

if ! grep -qF "$ENV_FILE" "$HOME/.bashrc" 2>/dev/null; then
  {
    printf '\n# >>> megafloyd devcontainer >>>\n'
    printf '[ -f %q ] && . %q\n' "$ENV_FILE" "$ENV_FILE"
    printf '# <<< megafloyd devcontainer <<<\n'
  } >>"$HOME/.bashrc"
fi

# The image ships a Go 1.26 toolchain. GOTOOLCHAIN=auto lets it fetch the
# exact patch named in go.mod from the public module proxy.
export GOTOOLCHAIN=auto

cd "$GO_DIR"
echo "megafloyd: $(go version)"
echo "megafloyd: downloading Go modules"
go mod download

# Match scripts/build-megafloyd.sh: `--always` falls back to the short commit
# when the clone has no tags, so a plain checkout never reports "devel".
VERSION="$(git -C "$REPO_ROOT" describe --tags --always --dirty 2>/dev/null || true)"
VERSION="${VERSION:-devel}"
COMMIT="$(git -C "$REPO_ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"

LDFLAGS="-s -w"
LDFLAGS+=" -X ${MODULE_PATH}/internal/version.Version=${VERSION}"
LDFLAGS+=" -X ${MODULE_PATH}/internal/version.Commit=${COMMIT}"

echo "megafloyd: building version $VERSION (commit $COMMIT)"
CGO_ENABLED=0 GOEXPERIMENT=greenteagc go build -trimpath -buildvcs=false \
  -ldflags "$LDFLAGS" \
  -o "$MEGAFLOYD_HOME/bin/megafloyd" .

mkdir -p "$HOME/.local/bin"
ln -sfn "$MEGAFLOYD_HOME/bin/megafloyd" "$HOME/.local/bin/megafloyd"

echo "megafloyd: built $MEGAFLOYD_HOME/bin/megafloyd"
reported="$("$MEGAFLOYD_HOME/bin/megafloyd" --version 2>&1)" || {
  echo "megafloyd: ERROR: built binary failed to report its version" >&2
  exit 1
}
printf '%s\n' "$reported"

if [[ $reported == *devel* ]]; then
  echo "megafloyd: ERROR: binary reports 'devel'; version and commit ldflags were not applied" >&2
  exit 1
fi
if [[ $reported != *"$VERSION"* ]]; then
  echo "megafloyd: ERROR: binary reports '$reported', expected version '$VERSION'" >&2
  exit 1
fi
