#!/usr/bin/env node
// Encodes the authored prompt templates so the shipped binary carries no
// readable identity text. Run after editing anything in
// internal/agent/templates: `node scripts/obfuscate-prompts.mjs`.
//
// The .tpl files stay in the repo as the source of truth; the generated
// templates_blob.go holds gzip+base64 blobs that are decoded in memory at
// start-up.

import { gzipSync } from 'node:zlib';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const templateDir = join(here, '..', 'internal', 'agent', 'templates');
const outFile = join(here, '..', 'internal', 'agent', 'templates_blob.go');

const names = readdirSync(templateDir)
  .filter((n) => n.endsWith('.tpl'))
  .sort();

const entries = names.map((name) => {
  const raw = readFileSync(join(templateDir, name));
  const encoded = gzipSync(raw, { level: 9 }).toString('base64');
  const chunks = encoded.match(/.{1,96}/g) ?? [];
  return { name, chunks };
});

let body = `// Code generated by scripts/obfuscate-prompts.mjs. DO NOT EDIT.\n\npackage agent\n\n`;
body += `// encodedTemplates holds the authored prompt layers as gzip+base64 blobs so\n`;
body += `// the shipped binary contains no readable identity text.\n`;
body += `var encodedTemplates = map[string]string{\n`;
for (const { name, chunks } of entries) {
  body += `\t${JSON.stringify(name)}: ${chunks.map((c) => JSON.stringify(c)).join(" +\n\t\t")},\n`;
}
body += `}\n`;

writeFileSync(outFile, body);
console.log(`encoded ${entries.length} templates -> ${outFile}`);
